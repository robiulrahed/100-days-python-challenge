"""
Problem 3: Multiple Assignment
Task: Assign length, width, and height (10, 5, 3) in a single line,
then print all of them in one print() statement.
"""

length, width, height = 10, 5, 3

print(length, width, height)

# Explanation:
# - Python allows assigning multiple variables in one line by separating
#   both the variable names and their values with commas.
# - The order matters: length gets 10, width gets 5, height gets 3,
#   matched position by position.
# - print() can take multiple values separated by commas, and it
#   automatically adds a space between them in the output.
