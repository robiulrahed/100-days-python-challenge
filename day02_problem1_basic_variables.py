"""
Problem 1: Basic Variable Creation
Task: Create three variables (book_title, price, is_available) with
string, float, and boolean data respectively, then print each one.
"""

book_title = "The Alchemist"
price = 12.99
is_available = True

print(book_title)
print(price)
print(is_available)

# Explanation:
# - book_title stores text data, so it's a string (wrapped in quotes).
# - price stores a decimal number, so it's a float.
# - is_available stores True/False, so it's a boolean.
# - Python figures out the data type automatically based on the value
#   we assign - we never had to declare the type ourselves.
